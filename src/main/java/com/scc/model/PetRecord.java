package model;

/**
 * Model class: one row of the pet_records table.
 * Attributes (5): ID, PET NAME, SPECIES, VACCINE, FEE.
 */
public class PetRecord {
    private int id;
    private String petName;
    private String species;
    private String vaccine;
    private double fee;

    // Used when reading from the database (ID already assigned)
    public PetRecord(int id, String petName, String species, String vaccine, double fee) {
        this.id = id;
        this.petName = petName;
        this.species = species;
        this.vaccine = vaccine;
        this.fee = fee;
    }

    // Used when creating a new record (ID is auto-generated by the database)
    public PetRecord(String petName, String species, String vaccine, double fee) {
        this(0, petName, species, vaccine, fee);
    }

    public int getId() { return id; }
    public String getPetName() { return petName; }
    public String getSpecies() { return species; }
    public String getVaccine() { return vaccine; }
    public double getFee() { return fee; }
}